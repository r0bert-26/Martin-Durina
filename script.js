// Bezpečné prepínanie sekcií
function navigateTo(viewId) {
    const targetView = document.getElementById(viewId);
    if (!targetView) {
        console.warn(`Sekcia s ID "${viewId}" sa v HTML nenachádza.`);
        return; // Zabráni skrytiu celej obrazovky
    }

    document.querySelectorAll('.view').forEach(view => {
        view.classList.remove('active');
    });

    targetView.classList.add('active');
    window.scrollTo(0, 0);
}

// Otvorenie kategórie (tolerantné k veľkým/malým písmenám a synonymám)
function openCategory(categoryKey) {
    if (!categoryKey) return;

    let key = categoryKey.toString().toLowerCase().trim();
    if (key === 'photography') key = 'photo';
    if (key === 'graphic') key = 'graphics';
    if (key === 'jewellery' || key === 'sperky') key = 'jewelry';

    const categoryData = portfolioData[key];
    if (!categoryData) {
        console.error(`Kategória "${categoryKey}" sa nenachádza v portfolioData.`);
        return;
    }

    const catTitle = document.getElementById('category-title');
    if (catTitle) catTitle.innerText = categoryData.title;

    const subcontainer = document.getElementById('subcategory-list');
    if (!subcontainer) return;
    subcontainer.innerHTML = '';

    categoryData.groups.forEach(group => {
        const groupSection = document.createElement('div');
        groupSection.className = 'group-section';

        const groupHeading = document.createElement('h3');
        groupHeading.className = 'group-heading';
        groupHeading.innerText = group.name;
        groupSection.appendChild(groupHeading);

        const grid = document.createElement('div');
        grid.className = 'subcategory-grid';

        group.projects.forEach(project => {
            const card = document.createElement('div');
            card.className = 'sub-card';
            card.onclick = () => openProject(project);
            card.innerHTML = `
                <img src="${project.cover}" alt="${project.title}" onerror="this.onerror=null; this.src='https://placehold.co/600x400/222/fff?text=Obr%C3%A1zok+nen%C3%A1jden%C3%BD';">
                <h4>${project.title}</h4>
            `;
            grid.appendChild(card);
        });

        groupSection.appendChild(grid);
        subcontainer.appendChild(groupSection);
    });

    navigateTo('view-category');
}

// Otvorenie projektu
function openProject(project) {
    const pTitle = document.getElementById('project-title');
    if (pTitle) pTitle.innerText = project.title;

    const pDesc = document.getElementById('project-description');
    if (pDesc) {
        if (project.description) {
            let textWithLinks = project.description;

            if (!textWithLinks.includes('<a ')) {
                textWithLinks = textWithLinks.replace(
                    /(https?:\/\/[^\s<]+)/g, 
                    '<a href="$1" target="_blank" rel="noopener noreferrer">$1</a>'
                );
            }

            const paragraphs = textWithLinks
                .trim()
                .split(/\r?\n\s*\r?\n/)
                .map(text => text.trim())
                .filter(text => text.length > 0)
                .map(text => `<p>${text}</p>`)
                .join('');
            pDesc.innerHTML = paragraphs;
        } else {
            pDesc.innerHTML = "<p>Bez popisu.</p>";
        }
    }

    const galleryContainer = document.getElementById('project-gallery');
    if (!galleryContainer) return;
    galleryContainer.innerHTML = '';

    let hasContent = false;

    // 1. Zobrazenie podkategórií (subGalleries)
    if (project.subGalleries && project.subGalleries.length > 0) {
        hasContent = true;
        const stacksGrid = document.createElement('div');
        stacksGrid.className = 'subgalleries-grid';

        project.subGalleries.forEach((subCat) => {
            if (!subCat.images || subCat.images.length === 0) return;

            const stackCard = document.createElement('div');
            stackCard.className = 'photo-stack-card';
            stackCard.style.cursor = 'pointer';
            stackCard.onclick = () => openLightbox(0, subCat.images);

            const coverImg = subCat.images[0];
            const count = subCat.images.length;
            const countText = count === 1 ? 'fotka' : (count >= 2 && count <= 4 ? 'fotky' : 'fotiek');

            stackCard.innerHTML = `
                <div class="photo-stack">
                    <img src="${coverImg}" alt="${subCat.title}" onerror="this.onerror=null; this.src='https://placehold.co/800x600/222/fff?text=Obr%C3%A1zok+nen%C3%A1jden%C3%BD';">
                </div>
                <div class="stack-info">
                    <h4>${subCat.title}</h4>
                    <span class="stack-count">${count} ${countText}</span>
                </div>
            `;

            stacksGrid.appendChild(stackCard);
        });

        galleryContainer.appendChild(stacksGrid);
    } 

    // 2. Zobrazenie klasických fotiek (images)
    if (project.images && project.images.length > 0) {
        hasContent = true;
        const grid = document.createElement('div');
        grid.className = 'project-gallery-grid';

        project.images.forEach((imgUrl, index) => {
            const img = document.createElement('img');
            img.src = imgUrl;
            img.alt = project.title;
            img.onclick = () => openLightbox(index, project.images);
            img.onerror = function() {
                this.onerror = null;
                this.src = 'https://placehold.co/800x600/222/fff?text=Obr%C3%A1zok+nen%C3%A1jden%C3%BD';
            };
            grid.appendChild(img);
        });
        galleryContainer.appendChild(grid);
    }

    if (!hasContent) {
        const placeholder = document.createElement('p');
        placeholder.style.color = '#666';
        placeholder.innerText = 'Žiadne ďalšie obrázky v galérii.';
        galleryContainer.appendChild(placeholder);
    }

    navigateTo('view-project');
}

/* --- LIGHTBOX GALÉRIA --- */
function openLightbox(index, images) {
    if (!images || images.length === 0) return;
    currentGallery = images;
    currentImgIndex = index;
    
    const modal = document.getElementById('image-modal');
    const modalImg = document.getElementById('modal-img');
    
    if (modal && modalImg) {
        modalImg.src = currentGallery[currentImgIndex];
        modal.style.display = 'flex';
        updateModalNav();
    }
}

function closeLightbox() {
    const modal = document.getElementById('image-modal');
    if (modal) {
        modal.style.display = 'none';
    }
}

function showNextImage() {
    if (currentGallery.length === 0) return;
    currentImgIndex = (currentImgIndex + 1) % currentGallery.length;
    const modalImg = document.getElementById('modal-img');
    if (modalImg) modalImg.src = currentGallery[currentImgIndex];
    updateModalNav();
}

function showPrevImage() {
    if (currentGallery.length === 0) return;
    currentImgIndex = (currentImgIndex - 1 + currentGallery.length) % currentGallery.length;
    const modalImg = document.getElementById('modal-img');
    if (modalImg) modalImg.src = currentGallery[currentImgIndex];
    updateModalNav();
}

function updateModalNav() {
    const prevBtn = document.querySelector('.modal-prev');
    const nextBtn = document.querySelector('.modal-next');
    const counter = document.getElementById('modal-counter');

    if (prevBtn && nextBtn) {
        const isSingle = currentGallery.length <= 1;
        prevBtn.style.display = isSingle ? 'none' : 'block';
        nextBtn.style.display = isSingle ? 'none' : 'block';
    }

    if (counter) {
        counter.innerText = `${currentImgIndex + 1} / ${currentGallery.length}`;
    }
}

// Inicializácia udalosťových poslucháčov
document.addEventListener('DOMContentLoaded', () => {
    const modal = document.getElementById('image-modal');
    const closeBtn = document.querySelector('.modal-close');
    const prevBtn = document.querySelector('.modal-prev');
    const nextBtn = document.querySelector('.modal-next');

    if (closeBtn) closeBtn.onclick = closeLightbox;
    
    if (prevBtn) {
        prevBtn.onclick = (e) => {
            e.stopPropagation();
            showPrevImage();
        };
    }
    
    if (nextBtn) {
        nextBtn.onclick = (e) => {
            e.stopPropagation();
            showNextImage();
        };
    }

    if (modal) {
        modal.onclick = (e) => {
            if (e.target === modal) closeLightbox();
        };
    }

    document.addEventListener('keydown', (e) => {
        if (modal && getComputedStyle(modal).display !== 'none') {
            if (e.key === 'Escape') closeLightbox();
            if (e.key === 'ArrowRight') showNextImage();
            if (e.key === 'ArrowLeft') showPrevImage();
        }
    });
});